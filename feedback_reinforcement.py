    def evaluate_improvements(self, test_submissions):
        """
        Evaluate the improvements in feedback quality after fine-tuning
        
        Args:
            test_submissions (list): List of test submissions to evaluate
            
        Returns:
            dict: Evaluation results
        """
        if self.ollama_client is None:
            return {"status": "error", "message": "Ollama client not initialized"}
        
        results = {
            "before_fine_tuning": [],
            "after_fine_tuning": [],
            "instructor_ratings": []
        }
        
        # Get some feedback pairs that weren't used in training
        eval_pairs = self.feedback_store["feedback_pairs"][-5:] if len(self.feedback_store["feedback_pairs"]) >= 5 else []
        
        if not eval_pairs:
            return {"status": "error", "message": "No evaluation data available"}
        
        for pair in tqdm(eval_pairs, desc="Evaluating model improvements"):
            # Get original feedback (before fine-tuning)
            original_feedback = pair["model_feedback"]
            
            # Get instructor feedback (ground truth)
            instructor_feedback = pair["instructor_feedback"]
            
            # Get feedback from potentially fine-tuned model
            try:
                # Generate feedback with current model
                response = self.ollama_client.generate(
                    model=self.config["ollama_model"],
                    prompt=f"Analyze this Java code for SOLID principles and provide feedback:\n\n```java\n{pair['original_code']}\n```"
                )
                new_feedback = response['response']
                
                # Store results
                results["before_fine_tuning"].append(original_feedback)
                results["after_fine_tuning"].append(new_feedback)
                results["instructor_ratings"].append(pair["instructor_rating"])
                
            except Exception as e:
                print(f"⚠️ Error generating feedback: {e}")
        
        # Calculate metrics
        if results["before_fine_tuning"]:
            # Add simple metrics here (would need more complex metrics in practice)
            # This is just a placeholder for demonstration purposes
            results["metrics"] = {
                "samples_evaluated": len(results["before_fine_tuning"]),
                "avg_instructor_rating": np.mean(results["instructor_ratings"]),
            }
        
        return results
    
    def get_learning_stats(self):
        """Get statistics on the learning progress"""
        if not self.feedback_store["feedback_pairs"]:
            return {
                "status": "no_data",
                "message": "No feedback data collected yet"
            }
        
        # Calculate statistics
        ratings = [pair["instructor_rating"] for pair in self.feedback_store["feedback_pairs"]]
        timestamps = [datetime.fromisoformat(pair["timestamp"]) for pair in self.feedback_store["feedback_pairs"]]
        
        # Sort by timestamp
        sorted_data = sorted(zip(timestamps, ratings), key=lambda x: x[0])
        sorted_timestamps, sorted_ratings = zip(*sorted_data)
        
        # Calculate moving average if there's enough data
        window_size = 5
        if len(sorted_ratings) >= window_size:
            moving_avg = [
                np.mean(sorted_ratings[i:i+window_size]) 
                for i in range(len(sorted_ratings) - window_size + 1)
            ]
        else:
            moving_avg = [np.mean(sorted_ratings)]
        
        return {
            "status": "success",
            "total_samples": len(self.feedback_store["feedback_pairs"]),
            "avg_rating": np.mean(ratings),
            "median_rating": np.median(ratings),
            "min_rating": min(ratings),
            "max_rating": max(ratings),
            "recent_trend": "improving" if len(moving_avg) > 1 and moving_avg[-1] > moving_avg[0] else "stable",
            "timestamps": [ts.isoformat() for ts in sorted_timestamps],
            "ratings": sorted_ratings,
            "moving_avg": moving_avg,
            "samples_needed_for_training": max(0, self.config["min_samples_for_fine_tuning"] - len(ratings))
        }


